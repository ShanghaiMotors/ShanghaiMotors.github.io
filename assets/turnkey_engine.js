function getCarOptions(carId, activeTrimName, activeSeats) {
    const raw = carOptionsDatabase[carId];
    if (!raw) {
        return { wheels: [], colors: [], interiors: [], additionalOptions: [] };
    }

    const cleanTrim = activeTrimName ? activeTrimName.trim().toUpperCase() : '';

    const filterItem = (item) => {
        if (!item) return false;
        if (item.availableTrims && item.availableTrims.length > 0 && cleanTrim) {
            const matchesTrim = item.availableTrims.some(t => {
                const target = t.trim().toUpperCase();
                if (target === cleanTrim) return true;
                if (cleanTrim.startsWith(target + ' ')) return true;
                if (cleanTrim.includes('(' + target + ')')) return true;
                // Avoid matching ULTRA when cleanTrim is ULTRA+
                if (cleanTrim.includes(target) && !cleanTrim.includes(target + '+')) return true;
                return false;
            });
            if (!matchesTrim) return false;
        }
        if (item.availableSeats && item.availableSeats.length > 0 && activeSeats) {
            if (!item.availableSeats.includes(activeSeats)) return false;
        }
        return true;
    };

    const cloneAndPrice = (item) => {
        const copy = Object.assign({}, item);
        if (copy.pricePerTrim && cleanTrim) {
            for (const [key, p] of Object.entries(copy.pricePerTrim)) {
                const target = key.trim().toUpperCase();
                if (cleanTrim === target || (cleanTrim.includes(target) && !cleanTrim.includes(target + '+'))) {
                    copy.priceUsd = p;
                    break;
                }
            }
        }
        return copy;
    };

    return {
        wheels: (raw.wheels || []).filter(filterItem).map(cloneAndPrice),
        colors: (raw.colors || []).filter(filterItem).map(cloneAndPrice),
        interiors: (raw.interiors || []).filter(filterItem).map(cloneAndPrice),
        additionalOptions: (raw.additionalOptions || []).filter(filterItem).map(cloneAndPrice)
    };
}

function parseNumericPower(powerStr) {
    if (!powerStr) return 0;
    const m = String(powerStr).match(/(\d[\d\s,]*)/);
    if (m) {
        return parseInt(m[1].replace(/[\s,]/g, ''), 10) || 0;
    }
    return 0;
}

function getTrimEngineCategory(trim) {
    const et = String(trim.engineType || '').toUpperCase();
    if (et.includes('REEV')) return 'REEV';
    if (et.includes('PHEV') || et.includes('ГИБРИД') || et.includes('HYBRID')) return 'PHEV';
    if (et.includes('EV') || et.includes('ЭЛЕКТРО') || et.includes('BEV')) return 'EV';
    return 'GAS';
}

function calculateTurnkeyPricing(trim, routeMode, liveRate, optionsUsd = 0) {
    const rate = liveRate || 84.43;
    const powerHp = (trim.eptsHp !== undefined) ? trim.eptsHp : parseNumericPower(trim.power);
    const category = getTrimEngineCategory(trim);

    const isEvOrReev = (category === 'EV' || category === 'REEV');
    const isUnder160 = (powerHp < 160);

    const canUseKg = (!isEvOrReev && !isUnder160);
    const route = canUseKg ? (routeMode || 'transit_kg') : 'direct_ru';

    const fobUsd = (trim.fobUsd || 0) + (optionsUsd || 0);
    const fobRub = Math.round(fobUsd * rate);

    let customsSum = 0;
    let utilFee = 0;
    const servicesRub = 120000;
    let fullPrice = 0;
    let directFullPrice = 0;

    if (trim.utilFeeRub !== undefined) {
        utilFee = trim.utilFeeRub;
    } else if (isUnder160) {
        utilFee = 3400;
    } else {
        if (category === 'EV' || category === 'REEV') {
            utilFee = 2193600;
        } else if (powerHp <= 200) {
            utilFee = 844800;
        } else if (powerHp <= 300) {
            utilFee = 1689600;
        } else {
            utilFee = 3201600;
        }
    }

    if (route === 'transit_kg') {
        let customsKgUsd = trim.customsKgUsd;
        if (!customsKgUsd) {
            if (powerHp > 400 || category === 'PHEV') customsKgUsd = 13500;
            else if (powerHp >= 200) customsKgUsd = 9500;
            else customsKgUsd = 4100;
        }
        const transitExpensesUsd = 800 + customsKgUsd + 2000;
        customsSum = Math.round(transitExpensesUsd * rate);
        fullPrice = fobRub + customsSum + utilFee + servicesRub;
    } else {
        let customsDutyRub = 0;
        if (category === 'EV') {
            customsDutyRub = Math.round(fobRub * 0.15 + (fobRub * 1.15) * 0.20);
        } else if (category === 'REEV') {
            const exciseRub = Math.round(powerHp * 618);
            const dutyBase = fobRub + exciseRub;
            customsDutyRub = Math.round(fobRub * 0.15 + exciseRub + (dutyBase * 1.15) * 0.20);
        } else {
            customsDutyRub = Math.round(fobRub * 0.48 + 21344);
        }

        const directFreightRub = Math.round(2500 * rate);
        customsSum = directFreightRub + customsDutyRub;
        fullPrice = fobRub + customsSum + utilFee + servicesRub;
    }

    if (canUseKg) {
        const dirDuty = Math.round(fobRub * 0.48 + 21344);
        const dirFreight = Math.round(2500 * rate);
        directFullPrice = fobRub + dirFreight + dirDuty + utilFee + servicesRub;
    } else {
        directFullPrice = fullPrice;
    }

    let transitKgPrice = fullPrice;
    if (canUseKg && route !== 'transit_kg') {
        let customsKgUsd = trim.customsKgUsd;
        if (!customsKgUsd) {
            if (powerHp > 400 || category === 'PHEV') customsKgUsd = 13500;
            else if (powerHp >= 200) customsKgUsd = 9500;
            else customsKgUsd = 4100;
        }
        transitKgPrice = fobRub + Math.round((800 + customsKgUsd + 2000) * rate) + utilFee + servicesRub;
    }

    const savingsVsDirect = canUseKg ? Math.max(0, directFullPrice - transitKgPrice) : 0;

    return {
        route,
        canUseKg,
        powerHp,
        category,
        fobUsd,
        fobRub,
        customsSum,
        utilFee,
        servicesRub,
        fullPrice,
        savingsVsDirect
    };
}

function formatDrive(drive, lang) {
    if (!drive) return '';
    if (lang === 'en') {
        if (/полный/i.test(drive) || /awd/i.test(drive) || /4wd/i.test(drive)) return 'AWD (All-Wheel Drive)';
        if (/задний/i.test(drive) || /rwd/i.test(drive)) return 'RWD (Rear-Wheel Drive)';
        if (/передний/i.test(drive) || /fwd/i.test(drive)) return 'FWD (Front-Wheel Drive)';
        return drive;
    }
    return drive;
}

function formatPower(power, lang) {
    if (!power) return '';
    if (lang === 'en') return power.replace('л.с.', 'hp');
    return power;
}

function formatAccel(accel, lang) {
    if (!accel) return '';
    if (lang === 'en') return accel.replace('сек', 's');
    return accel;
}

function formatRange(range, lang) {
    if (!range) return '';
    if (lang === 'en') return range.replace('км', 'km');
    return range;
}

function formatEngineType(engineType, lang) {
    if (!engineType) return '';
    if (lang === 'en') {
        return engineType
            .replace(/Гибрид\s*\(REEV\)/i, 'Hybrid (REEV)')
            .replace(/Гибрид\s*\(PHEV\)/i, 'Plug-in Hybrid (PHEV)')
            .replace(/Гибрид/i, 'Hybrid')
            .replace(/Электро\s*\(BEV\)/i, 'Electric (BEV)')
            .replace(/Электро/i, 'Electric (EV)')
            .replace(/EV\s*\(Электро\)/i, 'Electric (BEV)')
            .replace(/Бензин\s*\(ICE\)/i, 'Gasoline (ICE)')
            .replace(/Бензин/i, 'Gasoline');
    }
    return engineType;
}

function formatTrimName(name, lang) {
    if (!name) return '';
    if (lang === 'en') {
        return name.replace('(6 мест)', '(6 Seats)')
                   .replace('(5 мест)', '(5 Seats)')
                   .replace('(7 мест)', '(7 Seats)')
                   .replace('3-х моторный', 'Tri-Motor')
                   .replace('3-моторный', 'Tri-Motor')
                   .replace('Гибрид', 'Hybrid')
                   .replace('Электро', 'EV');
    }
    return name;
}

